--           contact_admin_select / contact_admin_update / contact_admin_delete


-- ---------------------------------------------------------------------------
-- 3) KONTROL — mevcut mesaj sayısı
-- ---------------------------------------------------------------------------
select count(*) as mesaj_sayisi,
       count(*) filter (where not is_read) as okunmamis
from public.contact_messages;
